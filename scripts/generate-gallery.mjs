import fs from "node:fs"
import path from "node:path"

const root = process.cwd()
const dir = path.join(root, "public/gallery")
const out = path.join(root, "src/lib/gallery.gen.ts")

const files = fs.readdirSync(dir).filter((f) => f.endsWith(".webp")).sort()

const slug = (name) => name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "")
const title = (name) =>
  name
    .replace(/[^a-z0-9]+/gi, " ")
    .trim()
    .split(" ")
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join(" ")

const items = files.map((f) => {
  const id = slug(f.replace(/\.webp$/, ""))
  const alt = title(f.replace(/\.webp$/, ""))
  return `  { id: ${JSON.stringify(id)}, alt: ${JSON.stringify(alt)}, src: ${JSON.stringify(`/gallery/${id}.webp`)} }`
})

const content = `// Auto-generated by scripts/generate-gallery.mjs. Do not edit.
// Re-run: npm run build (prebuild hook) or node scripts/generate-gallery.mjs

export type GalleryEntry = {
  id: string
  alt: string
  src: string
}

export const gallery: GalleryEntry[] = [
${items.join(",\n")}
]
`

fs.writeFileSync(out, content)
console.log(`Generated ${items.length} gallery items`)
